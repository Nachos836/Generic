internal static class Header
{
    public static CompilationUnitSyntax AddGenericHeader(this CompilationUnitSyntax compilation)
    {
        return compilation.AddHeaderWithDefinitions();
    }

    public static CompilationUnitSyntax AddHeaderWithDefinitions
    (
        this CompilationUnitSyntax compilation,
        params ReadOnlySpan<string?> definitionKeys
    ) {
        var trivia = new List<SyntaxTrivia>
        {
            Comment("// <auto-generated/>"),
            HardLineFeed,
            Trivia(IfDirectiveTrivia(
                condition: IdentifierName("UNITY_EDITOR"),
                isActive: true,
                branchTaken: true,
                conditionValue: true)),

            HardLineFeed,
            Trivia(NullableDirectiveTrivia(Token(EnableKeyword), isActive: true)),
            HardLineFeed
        };

        foreach (var definitionKey in definitionKeys)
        {
            if (definitionKey is null) continue;

            trivia.Add(Trivia(DefineDirectiveTrivia(definitionKey, isActive: true)));
            trivia.Add(LineFeed);
        }
        trivia.Add(HardLineFeed);

        return compilation.WithLeadingTrivia(trivia);
    }
}

internal static class Footer
{
    public static CompilationUnitSyntax AddGenericFooter(this CompilationUnitSyntax compilation)
    {
        return compilation.WithTrailingTrivia
        (
            HardCarriageReturn,
            Trivia(EndIfDirectiveTrivia(isActive: true)),
            CarriageReturn
        );
    }
}

