using Generator.InspectorAttributesEditor.Components;
using NUnit.Framework;

namespace Generator.InspectorAttributesEditor.Tests;

public sealed class DrawerOutputTests
{
    private const string WithCustomUI = """
        using System.Diagnostics;
        using InspectorAttributes;
        using JetBrains.Annotations;
        using UnityEngine;
        using UnityEngine.UIElements;

        namespace Generic.Samples
        {
            [ApplyCustomUIProcessing]
            internal sealed partial class BehaviourWithButtonAttribute : MonoBehaviour
            {
                [Button("Cyka!"), UsedImplicitly, Conditional("UNITY_EDITOR")]
                private void Test()
                {
                    UnityEngine.Debug.Log("Test");
                }

        #if UNITY_EDITOR
                internal partial class Drawer
                {
                    private partial void ApplyCustomUIProcessing(ref VisualElement defaultRoot,
                        ref VisualElement customRoot)
                    {
                    }
                }
        #endif
            }
        }
        """;

    private const string GlobalWithoutCustomUI = """
        using InspectorAttributes;
        using UnityEngine;

        internal sealed partial class Spawner : MonoBehaviour
        {
            [Button("Spawn \"all\"")]
            private void Spawn() { }

            [Button("Clear")]
            private void @event() { }
        }
        """;

    private static readonly string Version = Shared.Generator.Version.Current.ToString();

    private static readonly string WithCustomUIOwner = $$"""
        // <auto-generated/>

        #if UNITY_EDITOR

        #nullable enable

        #define INSPECTOR_BUTTONS_REQUIRED
        #define INSPECTOR_CUSTOM_UI_REQUIRED

        using System.CodeDom.Compiler;
        using System.Diagnostics;
        using System.Diagnostics.CodeAnalysis;
        using UnityEditor;
        using UnityEngine.UIElements;

        namespace Generic.Samples
        {
        	[ExcludeFromCodeCoverage, DebuggerNonUserCode, GeneratedCode("Generator.InspectorAttributesEditor", "{{Version}}")]
        	partial class BehaviourWithButtonAttribute
        	{
        		[ExcludeFromCodeCoverage, DebuggerNonUserCode, GeneratedCode("Generator.InspectorAttributesEditor", "{{Version}}"), CustomEditor(typeof(BehaviourWithButtonAttribute))]
        		internal sealed partial class Drawer : Editor
        		{
        			public override VisualElement CreateInspectorGUI()
        			{
        				var root = new VisualElement();
        				var defaultRoot = new VisualElement();
        				var customRoot = new VisualElement();

        				UnityEditor.UIElements.InspectorElement.FillDefaultInspector(defaultRoot, serializedObject, this);

        				WhenButtonAttributeDetected(customRoot);
        				ApplyCustomUIProcessing(ref defaultRoot, ref customRoot);

        				root.Add(defaultRoot);
        				root.Add(customRoot);

        				return root;
        			}

        			[Conditional("INSPECTOR_BUTTONS_REQUIRED")]
        			private partial void WhenButtonAttributeDetected(VisualElement root);
        			[Conditional("INSPECTOR_CUSTOM_UI_REQUIRED")]
        			private partial void ApplyCustomUIProcessing(ref VisualElement defaultRoot, ref VisualElement customRoot);
        		}
        	}
        }

        #endif
        """;

    private static readonly string WithCustomUIButtons = """
        // <auto-generated/>

        #if UNITY_EDITOR

        #nullable enable

        using UnityEditor;
        using UnityEngine.UIElements;

        namespace Generic.Samples
        {
        	partial class BehaviourWithButtonAttribute
        	{
        		partial class Drawer
        		{
        			private partial void WhenButtonAttributeDetected(VisualElement root)
        			{
        				var targetTyped = (BehaviourWithButtonAttribute)target;

        				root.Add(new Button(() => targetTyped.Test()) { text = "Cyka!" });
        			}
        		}
        	}
        }

        #endif
        """;

    private static readonly string GlobalWithoutCustomUIOwner = $$"""
        // <auto-generated/>

        #if UNITY_EDITOR

        #nullable enable

        #define INSPECTOR_BUTTONS_REQUIRED

        using System.CodeDom.Compiler;
        using System.Diagnostics;
        using System.Diagnostics.CodeAnalysis;
        using UnityEditor;
        using UnityEngine.UIElements;

        [ExcludeFromCodeCoverage, DebuggerNonUserCode, GeneratedCode("Generator.InspectorAttributesEditor", "{{Version}}")]
        partial class Spawner
        {
        	[ExcludeFromCodeCoverage, DebuggerNonUserCode, GeneratedCode("Generator.InspectorAttributesEditor", "{{Version}}"), CustomEditor(typeof(Spawner))]
        	internal sealed partial class Drawer : Editor
        	{
        		public override VisualElement CreateInspectorGUI()
        		{
        			var root = new VisualElement();
        			var defaultRoot = new VisualElement();
        			var customRoot = new VisualElement();

        			UnityEditor.UIElements.InspectorElement.FillDefaultInspector(defaultRoot, serializedObject, this);

        			WhenButtonAttributeDetected(customRoot);
        			ApplyCustomUIProcessing(ref defaultRoot, ref customRoot);

        			root.Add(defaultRoot);
        			root.Add(customRoot);

        			return root;
        		}

        		[Conditional("INSPECTOR_BUTTONS_REQUIRED")]
        		private partial void WhenButtonAttributeDetected(VisualElement root);
        		[Conditional("INSPECTOR_CUSTOM_UI_REQUIRED")]
        		private void ApplyCustomUIProcessing(ref VisualElement defaultRoot, ref VisualElement customRoot)
        		{
        			// Custom UI Processing will not be applied ...
        			return;
        		}
        	}
        }

        #endif
        """;

    private static readonly string GlobalWithoutCustomUIButtons = """
        // <auto-generated/>

        #if UNITY_EDITOR

        #nullable enable

        using UnityEditor;
        using UnityEngine.UIElements;

        partial class Spawner
        {
        	partial class Drawer
        	{
        		private partial void WhenButtonAttributeDetected(VisualElement root)
        		{
        			var targetTyped = (Spawner)target;

        			root.Add(new Button(() => targetTyped.@event()) { text = "Clear" });
        			root.Add(new Button(() => targetTyped.Spawn()) { text = "Spawn \"all\"" });
        		}
        	}
        }

        #endif
        """;

    private static readonly DrawerModel WithCustomUIModel = new()
    {
        Identity = "Generic.Samples.BehaviourWithButtonAttribute",
        NamespaceName = "Generic.Samples",
        OwnerName = "BehaviourWithButtonAttribute",
        RequiresCustomUI = true,
        Buttons = [new ButtonModel { Name = "Test", Label = "Cyka!" }]
    };

    private static readonly DrawerModel GlobalWithoutCustomUIModel = new()
    {
        Identity = "Spawner",
        NamespaceName = "",
        OwnerName = "Spawner",
        RequiresCustomUI = false,
        Buttons =
        [
            new ButtonModel { Name = "@event", Label = "Clear" },
            new ButtonModel { Name = "Spawn", Label = "Spawn \"all\"" }
        ]
    };

    [Test]
    public void ScopedDrawerWithCustomUIEmitsTodayOutput()
    {
        var (owner, buttons) = ScopedDrawer.Emit(WithCustomUIModel, Version);
        CodeAssert.AreEqual(WithCustomUIOwner, owner);
        CodeAssert.AreEqual(WithCustomUIButtons, buttons);
    }

    [Test]
    public void ScopedGlobalDrawerWithoutCustomUIEmitsTodayOutput()
    {
        var (owner, buttons) = ScopedDrawer.Emit(GlobalWithoutCustomUIModel, Version);
        CodeAssert.AreEqual(GlobalWithoutCustomUIOwner, owner);
        CodeAssert.AreEqual(GlobalWithoutCustomUIButtons, buttons);
    }

    [Test]
    public void ChainedDrawerWithCustomUIEmitsTodayOutput()
    {
        var (owner, buttons) = ChainedDrawer.Emit(WithCustomUIModel, Version);
        CodeAssert.AreEqual(WithCustomUIOwner, owner);
        CodeAssert.AreEqual(WithCustomUIButtons, buttons);
    }

    [Test]
    public void ChainedGlobalDrawerWithoutCustomUIEmitsTodayOutput()
    {
        var (owner, buttons) = ChainedDrawer.Emit(GlobalWithoutCustomUIModel, Version);
        CodeAssert.AreEqual(GlobalWithoutCustomUIOwner, owner);
        CodeAssert.AreEqual(GlobalWithoutCustomUIButtons, buttons);
    }

    [Test]
    public void DrawerWithCustomUIEmitsTodayOutput()
    {
        AssertOutput(WithCustomUI, WithCustomUIOwner, WithCustomUIButtons);
    }

    [Test]
    public void GlobalDrawerWithoutCustomUIEmitsTodayOutput()
    {
        AssertOutput(GlobalWithoutCustomUI, GlobalWithoutCustomUIOwner, GlobalWithoutCustomUIButtons);
    }

    private static void AssertOutput(string source, string expectedOwner, string expectedButtons)
    {
        var (files, diagnostics) = GeneratorRun.Run(source);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(files, Has.Count.EqualTo(2));

        var buttons = files.Single(static file => file.HintName.EndsWith(".buttons.g.cs"));
        CodeAssert.AreEqual(expectedOwner, files.Single(file => file != buttons).Text);
        CodeAssert.AreEqual(expectedButtons, buttons.Text);
    }
}
