using System.Collections.Generic;
using Shared.CodeGeneration.Chained;
using Shared.UnityBridge;
using UnityEditor;
using UnityEditor.UIElements;
using static Shared.CodeGeneration.Chained.Blocks;

namespace Generator.InspectorAttributesEditor.Components;

internal static class ChainedDrawer
{
    private const string ButtonsDefine = "INSPECTOR_BUTTONS_REQUIRED";
    private const string CustomUIDefine = "INSPECTOR_CUSTOM_UI_REQUIRED";
    private const string GeneratorName = "Generator.InspectorAttributesEditor";
    private const string DrawerName = "Drawer";
    private const string ButtonsMethod = "WhenButtonAttributeDetected";
    private const string CustomUIMethod = "ApplyCustomUIProcessing";
    private const string VisualElement = nameof(UnityEngine.UIElements.VisualElement);
    private const string AddChild = nameof(UnityEngine.UIElements.VisualElement.Add);
    private const string Button = nameof(UnityEngine.UIElements.Button);
    private const string ButtonText = nameof(UnityEngine.UIElements.Button.text);
    private const string UIElements = $"{nameof(UnityEngine)}.{nameof(UnityEngine.UIElements)}";

    private static readonly IReadOnlyList<string> OwnerUsings =
    [
        "System.CodeDom.Compiler",
        "System.Diagnostics",
        "System.Diagnostics.CodeAnalysis",
        nameof(UnityEditor),
        UIElements
    ];

    private static readonly IReadOnlyList<string> ButtonsUsings = [nameof(UnityEditor), UIElements];

    public static (string Owner, string Buttons) Emit(DrawerModel model, string version)
    {
        return (EmitOwnerFile(model, version), EmitButtonsFile(model));
    }

    private static string EmitOwnerFile(DrawerModel model, string version)
    {
        IReadOnlyList<string> defines = model.RequiresCustomUI ? [ButtonsDefine, CustomUIDefine] : [ButtonsDefine];
        var global = model.NamespaceName.Length == 0;
        var file = WriteOwner(WriteHeader(Code.File(), defines, OwnerUsings), model, version, global);
        return WriteOwner(file.Namespace(model.NamespaceName, global is false), model, version)
            .EndNamespace()
            .Gap().EndIfDirective()
            .EndFile();
    }

    private static string EmitButtonsFile(DrawerModel model)
    {
        var global = model.NamespaceName.Length == 0;
        var file = WriteButtons(WriteHeader(Code.File(), [], ButtonsUsings), model, global);
        return WriteButtons(file.Namespace(model.NamespaceName, global is false), model)
            .EndNamespace()
            .Gap().EndIfDirective()
            .EndFile();
    }

    private static FileChain WriteHeader(FileChain file, IReadOnlyList<string> defines, IReadOnlyList<string> usings)
    {
        return file.Comment("<auto-generated/>")
            .Gap().IfDirective(Defines.UnityEditor)
            .Gap().Nullable()
            .Gap().ForEach(defines, static (scope, symbol) => scope.Define(symbol))
            .Gap(defines.Count > 0).ForEach(usings, static (scope, name) => scope.Using(name));
    }

    private static TScope WriteOwner<TScope>(TScope scope, DrawerModel model, string version, bool when = true)
        where TScope : DeclarationChain<TScope>
    {
        var owner = WriteGeneratedAttributes(scope, version).Partial().Class(model.OwnerName, when);

        var drawer = WriteGeneratedAttributes(owner, version)
            .Attribute(nameof(CustomEditor), [TypeOf(T(model.OwnerName))])
            .Internal().Sealed().Partial().Class(DrawerName);
        return WriteDrawer(drawer, model.RequiresCustomUI).EndClass().EndClass();
    }

    private static TScope WriteGeneratedAttributes<TScope>(TScope scope, string version)
        where TScope : DeclarationChain<TScope>
    {
        return scope.Attribute("ExcludeFromCodeCoverage")
            .Attribute("DebuggerNonUserCode")
            .Attribute("GeneratedCode", [Lit(GeneratorName), Lit(version)]);
    }

    private static ClassChain<TOuter> WriteDrawer<TOuter>(ClassChain<TOuter> drawer, bool requiresCustomUI)
        where TOuter : class, IMemberHost
    {
        var inspectorGUI = drawer.Inherits(T(nameof(Editor)))
            .Public().Override().Method(T(VisualElement), nameof(Editor.CreateInspectorGUI)).Body();
        return WriteInspectorGUI(inspectorGUI).EndMethod()
            .Attribute("Conditional", [Lit(ButtonsDefine)])
            .Private().Partial().Method(T("void"), ButtonsMethod).Param(T(VisualElement), "root").EndMethod()
            .Attribute("Conditional", [Lit(CustomUIDefine)])
            .Private().Partial(requiresCustomUI).Method(T("void"), CustomUIMethod)
            .Ref().Param(T(VisualElement), "defaultRoot")
            .Ref().Param(T(VisualElement), "customRoot")
            .Body(requiresCustomUI is false).Comment("Custom UI Processing will not be applied ...").Return()
            .EndMethod();
    }

    private static MethodBodyChain<TOuter> WriteInspectorGUI<TOuter>(MethodBodyChain<TOuter> body)
        where TOuter : class, IMemberHost
    {
        return body.Var("root", New(T(VisualElement)))
            .Var("defaultRoot", New(T(VisualElement)))
            .Var("customRoot", New(T(VisualElement)))
            .Gap().Do(Id(nameof(UnityEditor)).Dot(nameof(UnityEditor.UIElements)).Dot(nameof(InspectorElement))
                .Dot(nameof(InspectorElement.FillDefaultInspector))
                .Call([Id("defaultRoot"), Id(nameof(Editor.serializedObject)), This()]))
            .Gap().Do(Id(ButtonsMethod).Call([Id("customRoot")]))
            .Do(Id(CustomUIMethod).Call([RefArg(Id("defaultRoot")), RefArg(Id("customRoot"))]))
            .Gap().Do(Id("root").Dot(AddChild).Call([Id("defaultRoot")]))
            .Do(Id("root").Dot(AddChild).Call([Id("customRoot")]))
            .Gap().Return(Id("root"));
    }

    private static TScope WriteButtons<TScope>(TScope scope, DrawerModel model, bool when = true)
        where TScope : DeclarationChain<TScope>
    {
        return scope.Partial().Class(model.OwnerName, when)
            .Partial().Class(DrawerName)
            .Private().Partial().Method(T("void"), ButtonsMethod).Param(T(VisualElement), "root").Body()
            .Var("targetTyped", Cast(T(model.OwnerName), Id(nameof(Editor.target))))
            .Gap().ForEach(model.Buttons, static (body, button) => body.Do(Id("root").Dot(AddChild).Call([
                New(T(Button), [Lambda().Arrow(Id("targetTyped").Dot(button.Name).Call())])
                    .Init([Id(ButtonText).Assign(Lit(button.Label))])
            ])))
            .EndMethod()
            .EndClass()
            .EndClass();
    }
}