using System.Collections.Generic;
using Shared.CodeGeneration.Scoped;
using UnityEditor;
using UnityEditor.UIElements;
using static Shared.CodeGeneration.Scoped.Blocks;

namespace Generator.InspectorAttributesEditor.Components;

internal static class ScopedDrawer
{
    private const string ButtonsDefine = "INSPECTOR_BUTTONS_REQUIRED";
    private const string CustomUIDefine = "INSPECTOR_CUSTOM_UI_REQUIRED";
    private const string GeneratorName = "Generator.InspectorAttributesEditor";
    private const string DrawerName = "Drawer";
    private const string ButtonsMethod = "WhenButtonAttributeDetected";
    private const string CustomUIMethod = "ApplyCustomUIProcessing";
    private const string VisualElement = nameof(UnityEngine.UIElements.VisualElement);
    private const string UIElements = $"{nameof(UnityEngine)}.{nameof(UnityEngine.UIElements)}";

    private static readonly IReadOnlyList<string> OwnerUsings =
    [
        "System.CodeDom.Compiler",
        "System.Diagnostics",
        "System.Diagnostics.CodeAnalysis",
        nameof(UnityEditor),
        UIElements
    ];

    private static readonly IReadOnlyList<string> ButtonsUsings = [nameof(UnityEditor), UIElements];

    public static (string Owner, string Buttons) Emit(DrawerModel model, string version)
    {
        return (EmitOwnerFile(model, version), EmitButtonsFile(model));
    }

    private static string EmitOwnerFile(DrawerModel model, string version)
    {
        IReadOnlyList<string> defines = model.RequiresCustomUI ? [ButtonsDefine, CustomUIDefine] : [ButtonsDefine];
        return Code.File(file =>
        {
            WriteHeader(file, defines, OwnerUsings);
            WriteOwner(file, model, version, model.NamespaceName.Length == 0);
            file.Namespace(model.NamespaceName, scope => WriteOwner(scope, model, version),
                model.NamespaceName.Length > 0);
            file.Gap().EndIfDirective();
        });
    }

    private static string EmitButtonsFile(DrawerModel model)
    {
        return Code.File(file =>
        {
            WriteHeader(file, [], ButtonsUsings);
            WriteButtons(file, model, model.NamespaceName.Length == 0);
            file.Namespace(model.NamespaceName, scope => WriteButtons(scope, model), model.NamespaceName.Length > 0);
            file.Gap().EndIfDirective();
        });
    }

    private static void WriteHeader(FileScope file, IReadOnlyList<string> defines, IReadOnlyList<string> usings)
    {
        file.Comment("<auto-generated/>")
            .Gap().IfDirective("UNITY_EDITOR")
            .Gap().Nullable()
            .Gap().ForEach(defines, static (scope, symbol) => scope.Define(symbol))
            .Gap(defines.Count > 0).ForEach(usings, static (scope, name) => scope.Using(name));
    }

    private static void WriteOwner<TScope>(TScope scope, DrawerModel model, string version, bool when = true)
        where TScope : DeclarationScope<TScope>
    {
        WriteGeneratedAttributes(scope, version);
        scope.Partial().Class(model.OwnerName, owner =>
        {
            WriteGeneratedAttributes(owner, version);
            owner.Attribute("CustomEditor", [TypeOf(T(model.OwnerName))])
                .Internal().Sealed().Partial().Class(DrawerName, drawer => WriteDrawer(drawer, model.RequiresCustomUI));
        }, when);
    }

    private static void WriteGeneratedAttributes<TScope>(TScope scope, string version)
        where TScope : DeclarationScope<TScope>
    {
        scope.Attribute("ExcludeFromCodeCoverage")
            .Attribute("DebuggerNonUserCode")
            .Attribute("GeneratedCode", [Lit(GeneratorName), Lit(version)]);
    }

    private static void WriteDrawer(TypeScope drawer, bool requiresCustomUI)
    {
        drawer.Inherits(T(nameof(Editor)))
            .Public().Override().Method(T(VisualElement), nameof(Editor.CreateInspectorGUI),
                static method => method.Body(WriteInspectorGUI))
            .Attribute("Conditional", [Lit(ButtonsDefine)])
            .Private().Partial().Method(T("void"), ButtonsMethod,
                static method => method.Param(T(VisualElement), "root"))
            .Attribute("Conditional", [Lit(CustomUIDefine)])
            .Private().Partial(requiresCustomUI).Method(T("void"), CustomUIMethod, method => method
                .Ref().Param(T(VisualElement), "defaultRoot")
                .Ref().Param(T(VisualElement), "customRoot")
                .Body(static body => body.Comment("Custom UI Processing will not be applied ...").Return(),
                    requiresCustomUI is false));
    }

    private static void WriteInspectorGUI(BodyScope body)
    {
        body.Var("root", New(T(VisualElement)))
            .Var("defaultRoot", New(T(VisualElement)))
            .Var("customRoot", New(T(VisualElement)))
            .Gap().Do(Id(nameof(UnityEditor)).Dot(nameof(UnityEditor.UIElements)).Dot(nameof(InspectorElement))
                .Dot(nameof(InspectorElement.FillDefaultInspector))
                .Call([Id("defaultRoot"), Id(nameof(Editor.serializedObject)), This()]))
            .Gap().Do(Id(ButtonsMethod).Call([Id("customRoot")]))
            .Do(Id(CustomUIMethod).Call([RefArg(Id("defaultRoot")), RefArg(Id("customRoot"))]))
            .Gap().Do(Id("root").Dot("Add").Call([Id("defaultRoot")]))
            .Do(Id("root").Dot("Add").Call([Id("customRoot")]))
            .Gap().Return(Id("root"));
    }

    private static void WriteButtons<TScope>(TScope scope, DrawerModel model, bool when = true)
        where TScope : DeclarationScope<TScope>
    {
        scope.Partial().Class(model.OwnerName, owner => owner
            .Partial().Class(DrawerName, drawer => drawer
                .Private().Partial().Method(T("void"), ButtonsMethod, method => method
                    .Param(T(VisualElement), "root")
                    .Body(body => body
                        .Var("targetTyped", Cast(T(model.OwnerName), Id("target")))
                        .Gap().ForEach(model.Buttons, static (statements, button) => statements
                            .Do(Id("root").Dot("Add").Call([
                                New(T("Button"), [Lambda().Arrow(Id("targetTyped").Dot(button.Name).Call())])
                                    .Init([Id("text").Assign(Lit(button.Label))])
                            ])))))), when);
    }
}